SONAR_RATE_LIMIT_WAIT_SECONDS = 65   # GitHub's search bucket is a rolling 60s window; +5s margin

SONAR_RATE_LIMIT_MAX_WAITS = 3       # 1 initial window + 3 waited windows = up to 4×30 = 120 calls

def _sonar_is_rate_limited(text):
    """Module-level so both _sonar_fetch() and sonar_sweep()'s raw gh calls (topic discovery,
    repo-view harvest) test the SAME text against the SAME rule — no drift between them."""
    t = (text or "").lower()
    return "403" in t or "429" in t or "rate limit" in t

def _sonar_wait_out_rate_limit(wait_tracker):
    """Sleep out one GitHub search-bucket window and record it. Returns False (no more retries
    left) once wait_tracker has already waited SONAR_RATE_LIMIT_MAX_WAITS times — the caller must
    then give up for real, same as the old immediate-short-circuit behavior, just later and louder."""
    if wait_tracker["count"] >= SONAR_RATE_LIMIT_MAX_WAITS:
        return False
    wait_tracker["count"] += 1
    time.sleep(SONAR_RATE_LIMIT_WAIT_SECONDS)
    wait_tracker["seconds"] += SONAR_RATE_LIMIT_WAIT_SECONDS
    return True

