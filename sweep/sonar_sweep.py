def sh(cmd, timeout=120, cwd=None):
    """Run a shell command with all five defensive guards."""
    try:
        r = subprocess.run(cmd, shell=True, capture_output=True, text=True,
                           timeout=timeout, stdin=subprocess.DEVNULL,
                           env=cli_env(), cwd=str(cwd) if cwd else None)
        # V3.11: THE BYTES BOUNDARY. Every gh call the sweep makes passes through here, so this one
        # counter is bytes_fetched for the whole run (reset by sonar_sweep). Measured, not estimated.
        _SH_ACCT["calls"] += 1
        _SH_ACCT["bytes"] += len(r.stdout or "") + len(r.stderr or "")
        return {"ok": True, "out": r.stdout, "err": r.stderr, "code": r.returncode}
    except subprocess.TimeoutExpired:
        return {"ok": False, "error": f"timed out after {timeout}s"}
    except Exception as e:
        return {"ok": False, "error": f"{type(e).__name__}: {e}"}

def _atomic_write(path, text):
    """Never leave a half-written ledger. Write beside, then rename."""
    d = path.parent
    d.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(d), prefix=".tmp-")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.replace(tmp, path)
    except Exception:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise

