def sonar_topic_slugs(core, cap=2):
    """GitHub topics are lowercase and hyphenated. Adjacent pairs are the ones that
    actually exist as curated topics (browser-automation, credit-report) — and the
    topic graph is where the 100k-star answers live that name+description never sees."""
    slugs, seen = [], set()
    for i in range(len(core) - 1):
        s = core[i] + "-" + core[i + 1]
        if s not in seen:
            seen.add(s)
            slugs.append(s)
    if not slugs and core:
        slugs.append(core[0])
    return slugs[:cap]

SONAR_SEARCH_JSON_FIELDS = ["fullName", "stargazersCount", "pushedAt", "description",
                            "url", "isArchived"]

_UNKNOWN_JSON_FIELD_RE = re.compile(r'Unknown JSON field:\s*"([^"]+)"')

def _sonar_fetch(gh, label, why, args, pool, timeout, fields=SONAR_SEARCH_JSON_FIELDS, degraded_fields=None,
                  wait_tracker=None):
    """One gh call. A FAILURE IS NEVER AN EMPTY RESULT.

    sh() has always returned out/err/code; the old cc_sonar read only `out`, so a
    401, a rate-limit, a timeout and a genuine zero were indistinguishable — all
    four printed `found: 0` with a friendly note. Proven live 2026-08-01:
    GH_TOKEN=bogus -> exit 1, EMPTY stdout, stderr "HTTP 401: Bad credentials",
    reported as `found: 0` and then cached for 30 minutes as `cached: true`.

    P3: gh's own --json field acceptance can differ by version/edition — P1 above
    is exactly that, discovered live. If a call fails with `Unknown JSON field:
    "<name>"`, that field is stripped from THIS call and it is retried ONCE; the
    field is also appended to the caller's `degraded_fields` list (shared across
    the whole sweep) so every later call builds its field list without it from
    the start, instead of re-discovering the same incompatibility per call. An
    angle is FAILED only if the retry also fails.

    S10 (2026-08-16): a 403/429 rate-limit is no longer an immediate FAILED. It waits out
    GitHub's rolling 60s search-bucket window (via wait_tracker, shared across the whole
    sweep so the bound is sweep-wide, not per-call) and retries the SAME call, up to
    SONAR_RATE_LIMIT_MAX_WAITS times. Only FAILED if still rate-limited after that.
    """
    if degraded_fields is None:
        degraded_fields = []
    if wait_tracker is None:
        wait_tracker = {"count": 0, "seconds": 0}

    def _attempt(field_list):
        c = (gh + " search repos " + args +
             " --sort stars --order desc --limit " + str(pool) +
             " --json " + ",".join(field_list))
        return c, sh(c, timeout=timeout)

    active_fields = [f for f in fields if f not in degraded_fields]
    cmd, r = _attempt(active_fields)
    if r.get("ok") and r.get("code") != 0:
        m = _UNKNOWN_JSON_FIELD_RE.search(r.get("err") or "")
        if m and m.group(1) in active_fields:
            degraded_fields.append(m.group(1))
            active_fields = [f for f in active_fields if f != m.group(1)]
            cmd, r = _attempt(active_fields)

    # S10: rate-limit wait-and-retry, bounded by wait_tracker (shared sweep-wide).
    while r.get("ok") and r.get("code") != 0 and _sonar_is_rate_limited(r.get("err") or ""):
        if not _sonar_wait_out_rate_limit(wait_tracker):
            break  # sweep-wide retry budget exhausted — fall through to FAILED below
        cmd, r = _attempt(active_fields)

    base = {"angle": label, "why": why, "cmd": cmd, "rows": [],
            "rate_limit_waits": wait_tracker["count"], "rate_limit_wait_seconds": wait_tracker["seconds"]}
    if not r.get("ok"):
        base["status"] = "FAILED"
        base["error"] = r.get("error") or "command did not complete"
        return base
    if r.get("code") != 0:
        err = (r.get("err") or "").strip().replace("\n", " ")[:300]
        base["status"] = "FAILED"
        base["error"] = "gh exit %s: %s" % (r.get("code"), err or "no stderr")
        return base
    txt = (r.get("out") or "").strip()
    if not txt:
        base["status"] = "FAILED"
        base["error"] = ("gh exited 0 but wrote nothing at all — that is an unexplained "
                         "silence, not a zero result (`--json` always prints at least [])")
        return base
    try:
        rows = json.loads(txt)
    except ValueError as e:
        base["status"] = "FAILED"
        base["error"] = "gh output was not JSON (%s): %s" % (e, txt[:200])
        return base
    if not isinstance(rows, list):
        base["status"] = "FAILED"
        base["error"] = "gh returned JSON that is not a list of repositories"
        return base
    base["status"] = "ok"
    base["rows"] = rows
    return base

def _sonar_failure(base, angles, why):
    """The shape a caller CANNOT mistake for 'nothing exists'.

    Deliberately omits `found` and `repos` entirely — a `found: 0` next to a
    failure is the exact lie this whole rebuild exists to delete. Same style as
    cc_contract's MISSING SOURCE error.
    """
    out = dict(base)
    out["error"] = why
    out["FAILED"] = "cc_sonar could not complete its search of GitHub"
    out["do_not_treat_as"] = ("an empty result, or proof that no prior art exists. Nothing is "
                              "reported because the search itself FAILED — NOT because GitHub "
                              "returned nothing. Fix the cause below, then re-run. This answer "
                              "was NOT cached.")
    out["angles"] = angles
    out["not_cached"] = "failures are never cached — a poisoned cache would serve this lie for 30 minutes"
    return out

