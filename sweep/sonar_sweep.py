def _sonar_glue_numeric_tokens(raw_toks):
    """V3.3/V2 (2026-08-07, live evidence): 'metro 2 credit' tokenized 'metro'
    and '2' SEPARATELY — '2' was then dropped as a bare number (no search
    signal), leaving bare 'metro' to pull WPF/metronome/metropolis junk. A
    standalone digit token immediately after a word is almost always PART OF
    THAT WORD ("metro 2", "web 3", "gpt 4") — glued onto the preceding token
    HERE, before classification ever sees either piece, so the merged form
    ('metro2') is what actually gets kept/dropped/searched/topic-discovered.
    Chains ("gpt","3","5" -> "gpt35") collapse into ONE report entry with the
    full origin list, not one entry per intermediate step. Never glues two
    bare digits together (nothing to anchor them to a word) — those still
    tokenize and drop independently, unchanged.

    Returns (glued_toks, glued_tokens_report) — report entries are
    {"from": [...original tokens...], "to": "<merged token>"}, one per
    position that actually changed; empty when nothing needed gluing.
    """
    out, origins = [], []
    for t in raw_toks:
        if out and t.isdigit() and not out[-1].isdigit():
            out[-1] = out[-1] + t
            origins[-1] = origins[-1] + [t]
        else:
            out.append(t)
            origins.append([t])
    report = [{"from": origins[i], "to": out[i]} for i in range(len(out)) if len(origins[i]) > 1]
    return out, report

def sonar_keywords(raw):
    """Extract search terms and RECORD every word removed, with a reason.

    Returns (core, query_terms, dropped, glued_tokens). `dropped` is an
    ordered list of (word, why) pairs. Nothing is ever removed silently —
    that silence was D2. `glued_tokens` is the report from
    _sonar_glue_numeric_tokens() — see V2/V3.3 there.
    """
    raw_toks = []
    for tok in _SONAR_TOKEN.findall(str(raw).lower()):
        w = tok.strip(".-")
        if w:
            raw_toks.append(w)
    glued_toks, glued_tokens = _sonar_glue_numeric_tokens(raw_toks)

    dropped, kept, seen = [], [], set()
    for w in glued_toks:
        if not any(ch.isalpha() for ch in w):
            dropped.append((w, "bare number — no search signal"))
        elif w in SONAR_STOP:
            dropped.append((w, "stopword"))
        elif len(w) < 2:
            dropped.append((w, "single character"))
        elif len(w) == 2 and w not in SONAR_TECH2:
            dropped.append((w, "two letters and not a known technical token"))
        elif w in seen:
            dropped.append((w, "duplicate of an earlier term"))
        else:
            seen.add(w)
            kept.append(w)

    core = list(kept)
    while len(core) > 2 and core[0] in SONAR_QUALIFIER:
        dropped.append((core[0], "leading qualifier — qualifies the subject, is not the subject"))
        core.pop(0)
    while len(core) > 2 and core[-1] in SONAR_GENERIC_HEAD:
        dropped.append((core[-1], "trailing generic head-noun — names the shape of the answer, not the subject"))
        core.pop()

    # GitHub ANDs every term. Measured 2026-08-01: three ANDed terms plus the star
    # floor is a cliff — "browser automation testing" matched repos, but the biggest
    # was 31 stars, so the >=50 floor emptied it while "browser automation" alone
    # clears 14k stars. Two terms is the usable window; the other angles carry the rest.
    query_terms = core[:2]
    for w in core[2:]:
        dropped.append((w, "outside the 2-term keyword window (GitHub ANDs every term) "
                           "— still used to derive topic slugs"))
    return core, query_terms, dropped, glued_tokens

def sonar_stop_pairs(raw, cap=2):
    """V3.44. Adjacent raw-word pairs that the stopword list would otherwise ERASE, offered to
    topic discovery as seeds. Measured 2026-09-19: "github prior art search cli multi-angle sweep"
    was sent as "github search" — "prior" and "art" are stopwords, so the pair "prior-art" was
    never tried, while the same problem worded "prior-art finder" surfaced r14dd/patent through
    topic:prior-art. A pair is only a SEED: the real topic graph (search/topics) decides whether
    it exists, exactly as it does for every other seed. Pure and separately testable."""
    toks = []
    for tok in _SONAR_TOKEN.findall(str(raw).lower()):
        w = tok.strip(".-")
        if w:
            toks.append(w)
    pairs = []
    for a, b in zip(toks, toks[1:]):
        if not (a in SONAR_STOP or b in SONAR_STOP):
            continue                      # nothing here was erased; the normal slugs cover it
        if a in SONAR_FUNCTION_WORDS or b in SONAR_FUNCTION_WORDS:
            continue                      # closed-class words never form a topic
        if len(a) >= 3 and len(b) >= 3 and a.isalpha() and b.isalpha():
            p = a + "-" + b
            if p not in pairs:
                pairs.append(p)
    return pairs[:cap]

