def sonar_rare_term(core, sent_words):
    """PA-11. The single RAREST core word, when it was not already sent as part of the main query.

    Why a single term and not a pair: measured directly against gh (sonar/priorart/RARE-PROBE-*.json),
    an ANDed rare PAIR returns nothing -- "inference contradiction" 0, "deduplication linkage" 0 --
    because a pair is rare in English precisely when few repositories put both words in their own
    text. The same words alone return 30 each, and "entailment" returns snli-entailment,
    Entailment-with-Tensorflow and vector-entailment: exactly the repositories the NLI query missed.

    Why relative rarity and not the common-word corpus: the name angle filters candidates by
    MEMBERSHIP in common-words-en.txt, so on a query whose every word is common English it has no
    candidate and never fires -- measured, name_token_candidates is [] for both
    "natural language inference contradiction detection" and "table structure recognition scanned
    document", the two worst pages of the campaign. Ranking by zipf always has a rarest word.

    The gate needs no constant: if the rarest word was already sent, this angle would just repeat
    the keyword angle."""
    z = _sonar_zipf()
    if not z["words"] or not core:
        return None
    zf = lambda w: z["words"].get(str(w).lower(), 0.0)
    w = sorted(core, key=lambda x: (zf(x), core.index(x)))[0]
    sent = {str(x).lower() for x in (sent_words or [])}
    return {"term": w, "zipf": zf(w), "already_sent": bool(str(w).lower() in sent),
            "fires": bool(str(w).lower() not in sent)}

def sonar_rare_pair(core, gap_threshold=None):
    """Return the rare-pair decision for a query's core words, or None when the table is missing.

    Pure and separately testable: the angle's firing rule is not buried inside sonar_sweep()."""
    z = _sonar_zipf()
    if not z["words"] or len(core) < 3:
        return None
    thr = SONAR_RARE_GAP if gap_threshold is None else gap_threshold
    zf = lambda w: z["words"].get(str(w).lower(), 0.0)
    pos = list(core[:2])
    rare = sorted(core, key=lambda w: (zf(w), core.index(w)))[:2]
    gap = (sum(zf(w) for w in pos) / 2.0) - (sum(zf(w) for w in rare) / 2.0)
    return {"positional": pos, "rarest": rare, "zipf_gap": round(gap, 2), "threshold": thr,
            "fires": bool(set(rare) != set(pos) and gap >= thr)}

