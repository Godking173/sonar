    # artefact file is read by tools, not by a model. `bytes_returned` and `packet_bytes` are
    # computed above, from `out`, and are untouched by this block BY CONSTRUCTION — `out` never
    # gains the key. Pins O-54/O-55 in cc-sonar-test.js assert exactly that, in both directions.
    # Fields are the ranker's own inputs and nothing else: everything else the page depends on
    # (min_stars, limit, keywords_kept) is already in the artefact.
    # angle_rank is GitHub's OWN returned position, 1-based, per angle. It is not derivable from
    # `top_by_angle`: that field re-sorts each angle's members by STARS, so the index a replay reads
    # there is a star rank wearing a retrieval rank's clothes — which is precisely what every RRF
    # variant this project has benched was actually fed. A rank-fusion ranker scored on star order is
    # not the ranker it claims to be, so the real order is recorded here once, at the only point in
    # the process where it still exists.
    _rank_by = {}
    for _a in angles:
        if _a.get("status") != "ok":
            continue
        for _i, _row in enumerate(_a.get("rows") or []):
            _fn = _row.get("fullName")
            if _fn:
                _rank_by.setdefault(_fn, {}).setdefault(str(_a["angle"]), _i + 1)
    _disk = dict(out)
    _disk["pool_full"] = sorted(
        [{"fullName": e["fullName"], "stars": e["stars"], "archived": bool(e["archived"]),
          "is_curated_list": bool(e["is_curated_list"]), "found_by": list(e["found_by"] or []),
          "angle_rank": _rank_by.get(e["fullName"], {}),
          # V3.26: the description GitHub already returned for this row. Not a new fetch — it is in
          # `merged` either way, and it is the only relevance signal on disk that is about the repo's
          # PURPOSE rather than its size or its provenance. Without it a page can only be scored by
          # the rank of one labelled repo, which measured blind on 3/5 to 5/5 of cases (D-B3a).
          "description": e.get("description") or ""}
         for e in merged.values()], key=lambda r: (-(r["stars"] or 0), r["fullName"]))
    _disk["pool_full_rule"] = ("Every repo this sweep deduped, with the exact fields the page ranker "
                               "consumed. A replay that ranks anything less than this is not ranking "
                               "the same universe the engine ranked, and its verdict is inadmissible.")
    try:
        if out.get("artifact"):
            jp = Path(out["artifact"]).with_suffix(".json")
            _atomic_write(jp, json.dumps(_disk, indent=1, sort_keys=True, default=str))
            out["artifact_json"] = str(jp)
    except Exception as _e:
        out["artifact_json"] = None
        out["artifact_json_error"] = str(_e)[:120]

    if not bad and not rate_limited:
        if not _no_cache:
            cache_put(key, out)  # successes only — a cached failure served the lie for 30 minutes
    log_event({"action": "sonar", "query": query, "angles": len(angles),
               "failed": len(bad), "matched": matched, "shown": len(shown)})
    return out


