def sonar_result_tier(found_by):
    """V1/v3.3 (2026-08-07, live evidence): a Metro 2 hunt's top-8 was
    dominated by TradingAgents (96k stars, found ONLY via snowball:finance /
    learned:finance) while the actual domain-specific hit (moov-io/metro2,
    127 stars, found via keyword+phrase) never made the shown list at all —
    it only ever showed up in top_by_angle ("best-from") lines. Star count
    rewards VIRALITY, not RELEVANCE: a repo a broad/exploratory angle found
    is not more relevant just because it happens to have more stars.

    Tier 0 — found by the query's OWN words (keyword/phrase) or a topic
    GitHub's real topic graph confirmed (topic:<slug>; NEVER
    topic-guessed:<slug>, which is an unconfirmed adjacent-word glue).
    Maximally query-specific.
    Tier 1 — found via learned:<term> (a PRIOR sweep's vocabulary) or readme
    (~10x recall, ~10x drift) but nothing more specific than that.
    Tier 2 — everything else: found only via snowball:*/topic-guessed:* (the
    two angle classes that produced the live bug) or any other broad/
    exploratory angle (e.g. synonym:*) — the necessary catch-all, since every
    result must land in exactly one tier.

    Checked in order; the FIRST tier whose condition is met wins, so a repo
    found by BOTH keyword and snowball is tier 0 — never diluted downward by
    its other, broader hits.
    """
    for fb in (found_by or []):
        if fb == "keyword" or fb == "phrase" or fb.startswith("topic:") or fb.startswith("code:") or fb.startswith("name:"):   # V3.12: source match = tier 0; D-G: a NAME match is the query's own word in the repo's identity
            return 0
    for fb in (found_by or []):
        if fb == "readme" or fb.startswith("learned:"):
            return 1
    return 2

